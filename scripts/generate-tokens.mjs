// Writes src/ui/tokens.css from the Book Reader design system's tokens.json (phase 18).
// Run with `npm run tokens` after the design changes; tests/config/design-tokens.test.ts checks
// that the stylesheet still matches. Deterministic: same input, same output.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const source = 'harness/context/design-system/tokens.json';
const design = JSON.parse(readFileSync(join(root, source), 'utf8'));

const themes = design.color.themes.map((theme) => theme.id);
const [first] = themes;
const selector = (theme) => (theme === first ? ':root' : `:root[data-theme='${theme}']`);
const alias = (value) => value.replace(/^\{([\w-]+)\}$/, 'var(--$1)');
const valueIn = (token, theme) =>
  typeof token.value === 'string'
    ? theme === first
      ? token.value
      : undefined
    : (token.value[theme] ?? (theme === first ? undefined : token.value[first]));

const lines = [
  `/* Generated by scripts/generate-tokens.mjs from ${source}. Do not edit by hand. */`,
  '',
];

for (const font of design.type.fonts) {
  lines.push(
    '@font-face {',
    `  font-family: '${font.family}';`,
    `  src: url('/${font.file}') format('woff2');`,
    `  font-weight: ${font.weight};`,
    `  font-style: ${font.style ?? 'normal'};`,
    // The system fallback shows at once; the page never waits for a font.
    '  font-display: swap;',
    '}',
    '',
  );
}

const darkThemes = new Set(['dark']);
/** Which token each theme's swatch takes, as in the design's ReadingSettings. */
const THEME_SWATCHES = { light: 'surface-raised', sepia: 'surface', dark: 'surface-raised' };
for (const theme of themes) {
  lines.push(`${selector(theme)} {`);
  lines.push(`  color-scheme: ${darkThemes.has(theme) ? 'dark' : 'light'};`);
  for (const token of [...design.color.tokens, ...design.shadow.tokens]) {
    const value = valueIn(token, theme);
    if (value !== undefined) lines.push(`  --${token.name}: ${alias(value)};`);
  }
  if (theme === first) {
    // App additions, not in the design: the PDF page itself. Pages are paper-white in every theme;
    // the theme filter over each page (app.css) darkens or tints them, so these never change.
    lines.push('  --page-paper: #ffffff;', '  --page-ink-muted: #655c50;');
    // The theme swatches in Reading settings (phase 19) show each theme's paper whatever theme is
    // on, so they are fixed: the colours the design's ReadingSettings source gives them.
    for (const [theme, name] of Object.entries(THEME_SWATCHES)) {
      const token = design.color.tokens.find((candidate) => candidate.name === name);
      lines.push(`  --theme-swatch-${theme}: ${valueIn(token, theme) ?? valueIn(token, first)};`);
    }
    for (const family of ['spacing', 'radius', 'size']) {
      for (const token of design[family].tokens) lines.push(`  --${token.name}: ${token.value};`);
    }
    for (const [name, stack] of Object.entries(design.type.families)) {
      lines.push(`  --font-${name}: ${stack};`);
    }
  }
  lines.push('}', '');
}

// Type styles as classes named after the style (`.title-md`, `.caption`).
for (const group of design.type.groups) {
  for (const style of group.styles) {
    lines.push(
      `.${style.name} {`,
      `  font-family: var(--font-${group.family});`,
      `  font-size: ${style.fontSize};`,
      `  line-height: ${style.lineHeight};`,
      `  font-weight: ${style.fontWeight};`,
    );
    if (style.letterSpacing) lines.push(`  letter-spacing: ${style.letterSpacing};`);
    lines.push('}', '');
  }
}

writeFileSync(join(root, 'src/ui/tokens.css'), `${lines.join('\n').trimEnd()}\n`);
